import Foundation

/// 界面语言。`auto` 跟着系统走，`zh` / `en` 是手动指定。
public enum AppLanguage: String, Codable, CaseIterable, Sendable {
    case auto
    case zh
    case en

    public var title: String {
        switch self {
        case .auto: return T("跟随系统")
        case .zh: return "简体中文"
        case .en: return "English"
        }
    }
}

/// 当前界面语言。程序启动和用户改设置时写。
///
/// 用中文原文当键，是为了让「还没翻译」的句子仍然能显示中文，而不是露出一个键名或空白。
/// 新加句子时把它包进 `T("中文")`，再在 `Table.english` 里补一行就行。
public enum Lang {
    /// 进程内共享。只在主线程写。
    public static var current: AppLanguage = .auto {
        didSet { cached = nil }
    }

    private static var cached: Bool?
    /// 系统偏好是不是英文。
    static var systemIsEnglish: Bool {
        if let cached { return cached }
        let preferred = Locale.preferredLanguages.first ?? "en"
        let value = preferred.lowercased().hasPrefix("en")
        cached = value
        return value
    }

    public static var isEnglish: Bool {
        switch current {
        case .en: return true
        case .zh: return false
        case .auto: return systemIsEnglish
        }
    }
}

/// 取当前语言下的这句话。翻译缺失时回落到中文原文。
public func T(_ chinese: String) -> String {
    Lang.isEnglish ? (Table.english[chinese] ?? chinese) : chinese
}

/// 带占位符的句子：`T("已 %@%", ["80"])`。占位符按顺序替换，避免每种语言调换语序时对不上。
/// 百分号直接写一个 `%`：这里不是 `String(format:)`，不做格式解析。
public func T(_ chinese: String, _ arguments: [String]) -> String {
    var text = T(chinese)
    for argument in arguments {
        guard let range = text.range(of: "%@") else { break }
        text.replaceSubrange(range, with: argument)
    }
    return text
}

