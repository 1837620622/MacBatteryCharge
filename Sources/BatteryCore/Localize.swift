import Foundation

/// 界面语言。`auto` 跟着系统走，其余是手动指定。
public enum AppLanguage: String, Codable, CaseIterable, Sendable {
    case auto
    /// 简体中文，也是源文字。
    case zh
    /// 繁體中文。
    case zhHant
    case en

    public var title: String {
        switch self {
        case .auto: return T("跟随系统")
        case .zh: return "简体中文"
        case .zhHant: return "繁體中文"
        case .en: return "English"
        }
    }
}

/// 当前界面语言。程序启动和用户改设置时写。
///
/// 用中文原文当键，是为了让「还没翻译」的句子仍然能显示中文，而不是露出一个键名或空白。
/// 新加句子时把它包进 `T("中文")`，再在 `Table.english` 和 `Table.traditional` 里各补一行。
public enum Lang {
    /// 进程内共享。只在主线程写。
    public static var current: AppLanguage = .auto {
        didSet { cached = nil }
    }

    private static var cached: AppLanguage?

    /// 实际用哪一种：`auto` 按系统首选语言定。简体、繁体、英文之外的语言先用英文，英文词典最全。
    public static var resolved: AppLanguage {
        if current != .auto { return current }
        if let cached { return cached }
        let value = systemLanguage
        cached = value
        return value
    }

    /// 系统首选语言。香港、澳门、台湾用繁体，其它中文用简体。
    static var systemLanguage: AppLanguage {
        let preferred = (Locale.preferredLanguages.first ?? "en").lowercased()
        if preferred.hasPrefix("zh-hant") || preferred.hasPrefix("zh-tw")
            || preferred.hasPrefix("zh-hk") || preferred.hasPrefix("zh-mo") {
            return .zhHant
        }
        if preferred.hasPrefix("zh") { return .zh }
        return .en
    }

    /// 系统偏好是不是英文。
    public static var systemIsEnglish: Bool { systemLanguage == .en }

    public static var isEnglish: Bool { resolved == .en }
}

/// 取当前语言下的这句话。翻译缺失时回落到中文原文。
public func T(_ chinese: String) -> String {
    switch Lang.resolved {
    case .auto, .zh: return chinese
    case .zhHant: return Table.traditional[chinese] ?? chinese
    case .en: return Table.english[chinese] ?? chinese
    }
}

/// 带占位符的句子：`T("已 %@%", ["80"])`。占位符按顺序替换，避免每种语言调换语序时对不上。
/// 百分号直接写一个 `%`：这里不是 `String(format:)`，不做格式解析。
public func T(_ chinese: String, _ arguments: [String]) -> String {
    var text = T(chinese)
    for argument in arguments {
        guard let range = text.range(of: "%@") else { break }
        text.replaceSubrange(range, with: argument)
    }
    return text
}

