#!/bin/bash
# 充电上限策略。只改系统允许充到的比例，不主动放电。
# 作息：06:00 市电来电，23:30 市电断电。断电后用电池写代码，并可自接充电宝。
# 06:00–20:59：上限 80%。来电后整天停在 80% 附近，避免满电搁置。
# 21:00–05:59：上限 100%。21:00 开始补电，给 23:30 断电前留出约 2.5 小时；
# 夜里保持 100%，充电宝接入后仍可充到 100%，不会被 80% 卡住。
set_profile() {
    local clock="${1:-}"
    [[ "$clock" =~ ^[0-9]{4}$ ]] || return 2
    local h="${clock:0:2}" m="${clock:2:2}"
    # HHMM 按四位字符串比较。不能用 -gt：前导 0 会被当成八进制。
    # shellcheck disable=SC2071
    [[ "$h" > "23" || "$m" > "59" ]] && return 2
    # shellcheck disable=SC2071
    if [[ "$clock" < "0600" || "$clock" > "2059" ]]; then
        printf '100\n'
    else
        printf '80\n'
    fi
}
